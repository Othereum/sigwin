fn main() {
    println!("cargo:rerun-if-changed=assets/app.manifest");
    println!("cargo:rerun-if-changed=assets/icon.ico");
    println!("cargo:rerun-if-changed=assets/icon-dev.ico");
    // ui/*.slint is compiled by crates/ui

    // `sigwin_dev`: a dev build (marked title, icon and version line; no self-install or
    // update). scripts/release.ps1 sets SIGWIN_RELEASE so none of it ships.
    println!("cargo::rustc-check-cfg=cfg(sigwin_dev)");
    println!("cargo:rerun-if-env-changed=SIGWIN_RELEASE");
    let dev = std::env::var_os("SIGWIN_RELEASE").is_none();
    if dev {
        println!("cargo:rustc-cfg=sigwin_dev");
        git_hash();
    }

    // third-party notices (`cargo about`, generated by the release workflow)
    println!("cargo:rerun-if-env-changed=SIGWIN_LICENSES");
    let out = std::path::Path::new(&std::env::var("OUT_DIR").unwrap()).join("licenses.html");
    match std::env::var("SIGWIN_LICENSES") {
        Ok(src) => {
            println!("cargo:rerun-if-changed={src}");
            std::fs::copy(&src, &out).expect("SIGWIN_LICENSES");
        }
        Err(_) => std::fs::write(
            &out,
            "<!doctype html><meta charset=utf-8><title>Sigwin</title><p>이 빌드에는 라이선스 고지가 들어 있지 않습니다.              <a href=\"https://github.com/Othereum/sigwin/releases/latest\">릴리스</a>의 licenses.html을 보세요.",
        )
        .unwrap(),
    }

    // this version's release notes for the "what's new" panel (`whatsnew.rs`); empty = none
    println!("cargo:rerun-if-env-changed=SIGWIN_NOTES");
    let out = std::path::Path::new(&std::env::var("OUT_DIR").unwrap()).join("release-notes.md");
    match std::env::var("SIGWIN_NOTES") {
        Ok(src) => {
            println!("cargo:rerun-if-changed={src}");
            std::fs::copy(&src, &out).expect("SIGWIN_NOTES");
        }
        Err(_) => std::fs::write(&out, "").unwrap(),
    }

    #[cfg(windows)]
    {
        let mut res = winresource::WindowsResource::new();
        res.set_icon("assets/icon.ico");
        if dev {
            // the dev build's icon (`tray::add_icon`, `gui::window::set_dev_icon`)
            res.set_icon_with_id("assets/icon-dev.ico", "2");
            // what scripts/release.ps1 checks to refuse a dev build
            res.set("SpecialBuild", "sigwin_dev");
        }
        res.set_manifest_file("assets/app.manifest");
        res.set("ProductName", "Sigwin");
        res.set("FileDescription", "Sigwin");
        res.set("Comments", "Unofficial Signal-compatible desktop client");
        res.compile().expect("windows resource");
    }
}

/// `SIGWIN_GIT_HASH`: short commit hash shown by dev builds, empty without git.
fn git_hash() {
    // rerun on a new commit or checkout: HEAD, the branch it points to, packed refs
    println!("cargo:rerun-if-changed=.git/HEAD");
    println!("cargo:rerun-if-changed=.git/packed-refs");
    if let Some(r) = std::fs::read_to_string(".git/HEAD").ok().and_then(|h| h.strip_prefix("ref: ").map(|r| r.trim().to_string())) {
        println!("cargo:rerun-if-changed=.git/{r}");
    }
    let hash = std::process::Command::new("git")
        .args(["rev-parse", "--short", "HEAD"])
        .output()
        .ok()
        .filter(|o| o.status.success())
        .map(|o| String::from_utf8_lossy(&o.stdout).trim().to_string())
        .unwrap_or_default();
    println!("cargo:rustc-env=SIGWIN_GIT_HASH={hash}");
}
